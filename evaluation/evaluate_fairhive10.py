#!/usr/bin/env python3
"""
Evaluate GeoComb workflow vs DeepBee on MDPI images using a manual-corrected reference.

Coordinate systems
------------------
Reference CSV and GeoComb workflow CSV are assumed to be in the 5000-px frame-crop
coordinate system.

DeepBee CSVs are assumed to be in raw image coordinates. This script transforms
DeepBee coordinates to the 5000-px frame-crop coordinate system using the frame
crop summary generated by the GeoComb pipeline.

Outputs
-------
- detection_metrics_by_image.csv
- detection_metrics_overall.csv
- end_to_end_class_metrics_by_method.csv
- count_error_by_image_class.csv
- count_error_summary.csv
- matched_predictions_all.csv
"""

from __future__ import annotations

import argparse
from pathlib import Path
import math
import numpy as np
import pandas as pd
import cv2


OUR_TO_DEEPBEE = {
    "Egg": "Egg",
    "Larvae": "Larvae",
    "Capped_pupae": "Capped_brood",
    "Pollen": "Pollen",
    "Capped_honey": "Honey",
    "Uncapped_honey": "Nectar",
    "Empty_cell": "Other",
    "Unbuilt_cell": "Other",
}

DEEPBEE_CLASSES = ["Egg", "Larvae", "Capped_brood", "Pollen", "Nectar", "Honey", "Other"]

OUR_CLASSES = [
    "Egg", "Larvae", "Capped_pupae", "Pollen",
    "Capped_honey", "Uncapped_honey", "Empty_cell", "Unbuilt_cell"
]


def pick_col(df: pd.DataFrame, candidates: list[str], kind: str) -> str:
    lower = {c.lower(): c for c in df.columns}
    for cand in candidates:
        if cand.lower() in lower:
            return lower[cand.lower()]
    raise ValueError(f"Could not find {kind} column. Columns: {list(df.columns)}")


def normalize_our_class(v) -> str:
    if isinstance(v, str):
        s = v.strip()
        if s in OUR_CLASSES:
            return s
        try:
            i = int(float(s))
            if 0 <= i < len(OUR_CLASSES):
                return OUR_CLASSES[i]
        except Exception:
            pass
        return s
    try:
        i = int(v)
        if 0 <= i < len(OUR_CLASSES):
            return OUR_CLASSES[i]
    except Exception:
        pass
    return str(v)


def normalize_deepbee_class(v) -> str:
    if isinstance(v, str):
        s = v.strip()
        if s in DEEPBEE_CLASSES:
            return s
        try:
            i = int(float(s))
            if 0 <= i < len(DEEPBEE_CLASSES):
                return DEEPBEE_CLASSES[i]
        except Exception:
            pass
        return s
    try:
        i = int(v)
        if 0 <= i < len(DEEPBEE_CLASSES):
            return DEEPBEE_CLASSES[i]
    except Exception:
        pass
    return str(v)


def find_image_path(image_root: Path, split: str, image_id: str) -> Path | None:
    roots = [image_root / split, image_root]
    for root in roots:
        for ext in [".jpg", ".JPG", ".jpeg", ".JPEG", ".png", ".PNG", ".tif", ".tiff", ".bmp", ".webp"]:
            p = root / f"{image_id}{ext}"
            if p.exists():
                return p
    return None


def find_our_csv(pred_root: Path, split: str, image_id: str) -> Path | None:
    candidates = [
        pred_root / split / image_id / "cell_predictions_3stage.csv",
        pred_root / split / image_id / "cell_predictions_8class.csv",
        pred_root / image_id / "cell_predictions_3stage.csv",
        pred_root / image_id / "cell_predictions_8class.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    hits = list(pred_root.rglob(f"{image_id}*cell_predictions*.csv"))
    return hits[0] if hits else None


def find_ref_csv(ref_root: Path, split: str, image_id: str) -> Path | None:
    candidates = [
        ref_root / split / image_id / "manual_reference_8class.csv",
        ref_root / image_id / "manual_reference_8class.csv",
        ref_root / split / f"{image_id}.csv",
        ref_root / f"{image_id}.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    hits = list(ref_root.rglob(f"{image_id}*reference*.csv"))
    return hits[0] if hits else None


def find_deepbee_csv(deepbee_root: Path, image_id: str) -> Path | None:
    candidates = [
        deepbee_root / f"{image_id}_deepbee_predictions.csv",
        deepbee_root / "per_image_csv" / f"{image_id}_deepbee_predictions.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    hits = list(deepbee_root.rglob(f"{image_id}*_deepbee_predictions.csv"))
    return hits[0] if hits else None


def load_reference(path: Path) -> pd.DataFrame:
    df0 = pd.read_csv(path)
    xcol = pick_col(df0, ["x", "center_x", "cx", "x_5000"], "x")
    ycol = pick_col(df0, ["y", "center_y", "cy", "y_5000"], "y")
    ccol = pick_col(df0, ["reference_class", "class", "final_class", "pred_class", "label"], "class")
    out = pd.DataFrame({
        "x": df0[xcol].astype(float),
        "y": df0[ycol].astype(float),
        "class8": [normalize_our_class(v) for v in df0[ccol]],
    })
    if "deleted" in df0.columns:
        keep = ~df0["deleted"].astype(bool)
        out = out.loc[keep].reset_index(drop=True)
    out["class7"] = out["class8"].map(OUR_TO_DEEPBEE).fillna(out["class8"])
    return out


def load_our_predictions(path: Path) -> pd.DataFrame:
    df0 = pd.read_csv(path)
    xcol = pick_col(df0, ["x", "center_x", "cx", "x_5000", "x_cls", "cell_x"], "x")
    ycol = pick_col(df0, ["y", "center_y", "cy", "y_5000", "y_cls", "cell_y"], "y")
    ccol = None
    for c in ["final_class", "pred_class", "class", "class_name", "label", "pred_label"]:
        if c in df0.columns:
            ccol = c
            break
    if ccol is None:
        raise ValueError(f"Could not find class column in {path}. Columns: {list(df0.columns)}")

    out = pd.DataFrame({
        "x": df0[xcol].astype(float),
        "y": df0[ycol].astype(float),
        "class8": [normalize_our_class(v) for v in df0[ccol]],
    })
    out["class7"] = out["class8"].map(OUR_TO_DEEPBEE).fillna(out["class8"])
    return out


def load_deepbee_predictions(path: Path) -> pd.DataFrame:
    df0 = pd.read_csv(path)
    xcol = pick_col(df0, ["x", "center_x", "cx"], "x")
    ycol = pick_col(df0, ["y", "center_y", "cy"], "y")
    if "deepbee_class" in df0.columns:
        classes = [normalize_deepbee_class(v) for v in df0["deepbee_class"]]
    elif "deepbee_class_id" in df0.columns:
        classes = [normalize_deepbee_class(v) for v in df0["deepbee_class_id"]]
    elif "deepbee_col3" in df0.columns:
        classes = [normalize_deepbee_class(v) for v in df0["deepbee_col3"]]
    else:
        raise ValueError(f"Could not find DeepBee class column in {path}. Columns: {list(df0.columns)}")
    return pd.DataFrame({
        "x_raw": df0[xcol].astype(float),
        "y_raw": df0[ycol].astype(float),
        "class7": classes,
    })


def infer_crop_summary_path(crop_root: Path) -> Path | None:
    candidates = [
        crop_root / "summaries" / "frame_detection_crop_magenta_summary.csv",
        crop_root / "00_frame_crop_masked_resize_3000_5000_puremagenta_fromraw_v1" / "summaries" / "frame_detection_crop_magenta_summary.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    hits = list(crop_root.rglob("*summary*.csv"))
    return hits[0] if hits else None


def get_summary_row(summary: pd.DataFrame, image_id: str) -> pd.Series | None:
    for c in ["image_id", "stem", "id", "file_stem", "name"]:
        if c in summary.columns:
            m = summary[summary[c].astype(str) == str(image_id)]
            if len(m):
                return m.iloc[0]
    # Try any column that contains filename/stem
    for c in summary.columns:
        vals = summary[c].astype(str)
        m = summary[vals.str.contains(str(image_id), regex=False, na=False)]
        if len(m):
            return m.iloc[0]
    return None


def find_value(row: pd.Series, candidates: list[str]):
    lower = {str(k).lower(): k for k in row.index}
    for cand in candidates:
        if cand.lower() in lower:
            return row[lower[cand.lower()]]
    # fuzzy contains
    for cand in candidates:
        c = cand.lower()
        for key_lower, key in lower.items():
            if c == key_lower or c in key_lower:
                return row[key]
    return None


def parse_bbox_from_row(row: pd.Series):
    x1 = find_value(row, ["crop_x1", "crop_x0", "bbox_x1", "bbox_x0", "orig_x1", "orig_x0", "raw_x1", "raw_x0", "x1", "x0", "xmin", "x_min", "left"])
    y1 = find_value(row, ["crop_y1", "crop_y0", "bbox_y1", "bbox_y0", "orig_y1", "orig_y0", "raw_y1", "raw_y0", "y1", "y0", "ymin", "y_min", "top"])
    x2 = find_value(row, ["crop_x2", "bbox_x2", "orig_x2", "raw_x2", "x2", "xmax", "x_max", "right"])
    y2 = find_value(row, ["crop_y2", "bbox_y2", "orig_y2", "raw_y2", "y2", "ymax", "y_max", "bottom"])
    w = find_value(row, ["crop_w", "bbox_w", "orig_w", "raw_w", "width", "w"])
    h = find_value(row, ["crop_h", "bbox_h", "orig_h", "raw_h", "height", "h"])

    try:
        x1 = float(x1); y1 = float(y1)
    except Exception:
        return None

    if x2 is not None and y2 is not None:
        try:
            x2 = float(x2); y2 = float(y2)
            return x1, y1, x2, y2
        except Exception:
            pass

    if w is not None and h is not None:
        try:
            w = float(w); h = float(h)
            return x1, y1, x1 + w, y1 + h
        except Exception:
            pass

    return None


def transform_deepbee_to_crop5000(df: pd.DataFrame, image_id: str, summary: pd.DataFrame | None,
                                  image_root_5000: Path, split: str) -> pd.DataFrame:
    # If no summary is available, assume coordinates are already in same coordinate system.
    out = df.copy()

    img_path = find_image_path(image_root_5000, split, image_id)
    if img_path is None:
        raise FileNotFoundError(f"Could not find 5000 crop image for {image_id} in {image_root_5000}")
    img = cv2.imread(str(img_path))
    if img is None:
        raise RuntimeError(f"Failed to read image {img_path}")
    out_h, out_w = img.shape[:2]

    if summary is None:
        out["x"] = out["x_raw"]
        out["y"] = out["y_raw"]
        return out

    row = get_summary_row(summary, image_id)
    if row is None:
        print(f"[WARN] No crop summary row for {image_id}; assuming DeepBee coords already match crop coords.")
        out["x"] = out["x_raw"]
        out["y"] = out["y_raw"]
        return out

    bbox = parse_bbox_from_row(row)
    if bbox is None:
        print(f"[WARN] Could not parse bbox for {image_id}. Summary columns: {list(summary.columns)}")
        print("[WARN] Assuming DeepBee coords already match crop coords.")
        out["x"] = out["x_raw"]
        out["y"] = out["y_raw"]
        return out

    x1, y1, x2, y2 = bbox
    bw = max(1e-9, x2 - x1)
    bh = max(1e-9, y2 - y1)
    sx = out_w / bw
    sy = out_h / bh

    out["x"] = (out["x_raw"] - x1) * sx
    out["y"] = (out["y_raw"] - y1) * sy

    # keep only points within crop plus small margin
    margin = max(out_w, out_h) * 0.05
    out = out[(out["x"] >= -margin) & (out["x"] <= out_w + margin) &
              (out["y"] >= -margin) & (out["y"] <= out_h + margin)].reset_index(drop=True)
    return out


def estimate_pitch(ref: pd.DataFrame) -> float:
    pts = ref[["x","y"]].to_numpy(float)
    if len(pts) < 5:
        return 50.0
    try:
        from scipy.spatial import cKDTree
        d, _ = cKDTree(pts).query(pts, k=2)
        pitch = float(np.median(d[:,1]))
        if math.isfinite(pitch) and pitch > 0:
            return pitch
    except Exception:
        pass
    # fallback small sample
    ds = []
    for i in range(min(len(pts), 500)):
        d = np.sqrt(((pts - pts[i])**2).sum(axis=1))
        d = d[d > 1e-6]
        if len(d):
            ds.append(float(np.min(d)))
    return float(np.median(ds)) if ds else 50.0


def match_points(ref: pd.DataFrame, pred: pd.DataFrame, threshold: float):
    ref_pts = ref[["x","y"]].to_numpy(float)
    pred_pts = pred[["x","y"]].to_numpy(float)
    if len(ref_pts) == 0 or len(pred_pts) == 0:
        return [], list(range(len(ref_pts))), list(range(len(pred_pts)))

    # Build candidate pairs within threshold, then greedy by distance.
    pairs = []
    try:
        from scipy.spatial import cKDTree
        tree = cKDTree(pred_pts)
        for i, pt in enumerate(ref_pts):
            idxs = tree.query_ball_point(pt, threshold)
            for j in idxs:
                dist = float(np.linalg.norm(pt - pred_pts[j]))
                pairs.append((dist, i, int(j)))
    except Exception:
        for i, r in enumerate(ref_pts):
            d = np.sqrt(((pred_pts - r)**2).sum(axis=1))
            for j in np.where(d <= threshold)[0]:
                pairs.append((float(d[j]), i, int(j)))

    pairs.sort()
    used_ref = set()
    used_pred = set()
    matches = []
    for dist, i, j in pairs:
        if i not in used_ref and j not in used_pred:
            matches.append((i, j, dist))
            used_ref.add(i)
            used_pred.add(j)

    unmatched_ref = [i for i in range(len(ref_pts)) if i not in used_ref]
    unmatched_pred = [j for j in range(len(pred_pts)) if j not in used_pred]
    return matches, unmatched_ref, unmatched_pred


def detection_metrics(tp, fp, fn):
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2*precision*recall/(precision+recall) if precision+recall else 0.0
    return precision, recall, f1


def class_metrics_from_records(records, classes=DEEPBEE_CLASSES):
    rows = []
    for c in classes:
        tp = sum(1 for r in records if r["ref_class7"] == c and r["pred_class7"] == c and r["status"] == "matched")
        fp = sum(1 for r in records if r["pred_class7"] == c and not (r["ref_class7"] == c and r["status"] == "matched"))
        fn = sum(1 for r in records if r["ref_class7"] == c and not (r["pred_class7"] == c and r["status"] == "matched"))
        p, rec, f1 = detection_metrics(tp, fp, fn)
        rows.append({"class": c, "precision": p, "recall": rec, "f1": f1, "tp": tp, "fp": fp, "fn": fn, "support": tp + fn})
    return pd.DataFrame(rows)


def evaluate_method(image_id: str, method: str, ref: pd.DataFrame, pred: pd.DataFrame, threshold: float):
    matches, unref, unpred = match_points(ref, pred, threshold)
    tp, fp, fn = len(matches), len(unpred), len(unref)
    precision, recall, f1 = detection_metrics(tp, fp, fn)

    det = {
        "image_id": image_id,
        "method": method,
        "n_reference": len(ref),
        "n_predicted": len(pred),
        "match_threshold_px": threshold,
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "precision": precision,
        "recall_cdr": recall,
        "f1": f1,
        "absolute_count_error": abs(len(pred) - len(ref)),
        "relative_count_error": abs(len(pred) - len(ref)) / len(ref) if len(ref) else np.nan,
    }

    records = []
    for i, j, dist in matches:
        records.append({
            "image_id": image_id,
            "method": method,
            "status": "matched",
            "distance_px": dist,
            "ref_index": i,
            "pred_index": j,
            "ref_x": ref.iloc[i]["x"],
            "ref_y": ref.iloc[i]["y"],
            "pred_x": pred.iloc[j]["x"],
            "pred_y": pred.iloc[j]["y"],
            "ref_class7": ref.iloc[i]["class7"],
            "pred_class7": pred.iloc[j]["class7"],
            "correct_class": ref.iloc[i]["class7"] == pred.iloc[j]["class7"],
        })
    for i in unref:
        records.append({
            "image_id": image_id,
            "method": method,
            "status": "missed_reference",
            "distance_px": np.nan,
            "ref_index": i,
            "pred_index": np.nan,
            "ref_x": ref.iloc[i]["x"],
            "ref_y": ref.iloc[i]["y"],
            "pred_x": np.nan,
            "pred_y": np.nan,
            "ref_class7": ref.iloc[i]["class7"],
            "pred_class7": np.nan,
            "correct_class": False,
        })
    for j in unpred:
        records.append({
            "image_id": image_id,
            "method": method,
            "status": "false_prediction",
            "distance_px": np.nan,
            "ref_index": np.nan,
            "pred_index": j,
            "ref_x": np.nan,
            "ref_y": np.nan,
            "pred_x": pred.iloc[j]["x"],
            "pred_y": pred.iloc[j]["y"],
            "ref_class7": np.nan,
            "pred_class7": pred.iloc[j]["class7"],
            "correct_class": False,
        })

    return det, records


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--image_root_5000", required=True, type=Path)
    ap.add_argument("--geocomb_pred_root", required=True, type=Path)
    ap.add_argument("--deepbee_csv_root", required=True, type=Path)
    ap.add_argument("--reference_root", required=True, type=Path)
    ap.add_argument("--out_root", required=True, type=Path)
    ap.add_argument("--split", default="test")
    ap.add_argument("--crop_summary", type=Path, default=None)
    ap.add_argument("--match_threshold_ratio", type=float, default=0.50)
    ap.add_argument("--match_threshold_px", type=float, default=None)
    args = ap.parse_args()

    args.out_root.mkdir(parents=True, exist_ok=True)

    if args.crop_summary is None:
        # infer from image root ancestry
        candidates = []
        p = args.image_root_5000
        for parent in [p] + list(p.parents):
            candidates.extend(parent.rglob("frame_detection_crop_magenta_summary.csv"))
            if candidates:
                break
        args.crop_summary = candidates[0] if candidates else None

    summary = None
    if args.crop_summary is not None and args.crop_summary.exists():
        summary = pd.read_csv(args.crop_summary)
        print("[INFO] Using crop summary:", args.crop_summary)
    else:
        print("[WARN] No crop summary found; DeepBee coords assumed to match reference coords.")

    # image ids from reference files
    ref_files = sorted((args.reference_root / args.split).glob("*/manual_reference_8class.csv"))
    if not ref_files:
        ref_files = sorted(args.reference_root.rglob("*manual_reference_8class.csv"))
    if not ref_files:
        raise FileNotFoundError(f"No manual_reference_8class.csv found in {args.reference_root}")

    det_rows = []
    all_records = []
    count_rows = []

    for ref_csv in ref_files:
        image_id = ref_csv.parent.name
        ref = load_reference(ref_csv)
        pitch = estimate_pitch(ref)
        threshold = args.match_threshold_px if args.match_threshold_px is not None else pitch * args.match_threshold_ratio

        our_csv = find_our_csv(args.geocomb_pred_root, args.split, image_id)
        deep_csv = find_deepbee_csv(args.deepbee_csv_root, image_id)
        if our_csv is None:
            print(f"[WARN] Missing GeoComb workflow CSV for {image_id}; skip")
            continue
        if deep_csv is None:
            print(f"[WARN] Missing DeepBee CSV for {image_id}; skip")
            continue

        geocomb = load_our_predictions(our_csv)
        deep_raw = load_deepbee_predictions(deep_csv)
        deep = transform_deepbee_to_crop5000(deep_raw, image_id, summary, args.image_root_5000, args.split)

        for method, pred in [("GeoComb", geocomb), ("DeepBee", deep)]:
            det, records = evaluate_method(image_id, method, ref, pred, threshold)
            det["estimated_pitch_px"] = pitch
            det_rows.append(det)
            all_records.extend(records)

            ref_counts = ref["class7"].value_counts().to_dict()
            pred_counts = pred["class7"].value_counts().to_dict()
            for c in DEEPBEE_CLASSES:
                manual = int(ref_counts.get(c, 0))
                auto = int(pred_counts.get(c, 0))
                count_rows.append({
                    "image_id": image_id,
                    "method": method,
                    "class": c,
                    "manual_count": manual,
                    "predicted_count": auto,
                    "count_error": auto - manual,
                    "absolute_count_error": abs(auto - manual),
                    "absolute_percentage_error": abs(auto - manual) / manual if manual > 0 else np.nan,
                })

        print(
            f"[OK] {image_id}: ref={len(ref)} "
            f"geocomb={len(geocomb)} deepbee={len(deep)} "
            f"threshold={threshold:.2f}"
        )

    det_by = pd.DataFrame(det_rows)
    records_df = pd.DataFrame(all_records)
    count_df = pd.DataFrame(count_rows)

    det_by.to_csv(args.out_root / "detection_metrics_by_image.csv", index=False)
    records_df.to_csv(args.out_root / "matched_predictions_all.csv", index=False)
    count_df.to_csv(args.out_root / "count_error_by_image_class.csv", index=False)

    # Overall detection metrics from pooled TP/FP/FN
    overall_rows = []
    for method, g in det_by.groupby("method"):
        tp = int(g["tp"].sum()); fp = int(g["fp"].sum()); fn = int(g["fn"].sum())
        p, r, f1 = detection_metrics(tp, fp, fn)
        overall_rows.append({
            "method": method,
            "images": g["image_id"].nunique(),
            "n_reference": int(g["n_reference"].sum()),
            "n_predicted": int(g["n_predicted"].sum()),
            "tp": tp, "fp": fp, "fn": fn,
            "precision": p, "recall_cdr": r, "f1": f1,
            "mean_relative_count_error": float(g["relative_count_error"].mean()),
            "median_relative_count_error": float(g["relative_count_error"].median()),
        })
    overall = pd.DataFrame(overall_rows)
    overall.to_csv(args.out_root / "detection_metrics_overall.csv", index=False)

    # End-to-end classification metrics
    class_metric_rows = []
    for method, g in records_df.groupby("method"):
        m = class_metrics_from_records(g.to_dict("records"), DEEPBEE_CLASSES)
        m.insert(0, "method", method)
        class_metric_rows.append(m)
    class_metrics = pd.concat(class_metric_rows, ignore_index=True)
    class_metrics.to_csv(args.out_root / "end_to_end_class_metrics_by_method.csv", index=False)

    # overall classification-on-matched accuracy
    acc_rows = []
    for method, g in records_df.groupby("method"):
        matched = g[g["status"] == "matched"]
        acc_rows.append({
            "method": method,
            "matched_cells": len(matched),
            "classification_accuracy_on_matched": float(matched["correct_class"].mean()) if len(matched) else np.nan,
            "end_to_end_correctly_localized_and_classified": int((matched["correct_class"] == True).sum()),
            "end_to_end_correct_rate_vs_reference": int((matched["correct_class"] == True).sum()) / int(det_by.loc[det_by["method"] == method, "n_reference"].sum()),
        })
    pd.DataFrame(acc_rows).to_csv(args.out_root / "classification_accuracy_summary.csv", index=False)

    count_summary = (count_df.groupby(["method", "class"], as_index=False)
                     .agg(manual_count=("manual_count","sum"),
                          predicted_count=("predicted_count","sum"),
                          mean_abs_percentage_error=("absolute_percentage_error","mean"),
                          mean_abs_count_error=("absolute_count_error","mean"),
                          total_abs_count_error=("absolute_count_error","sum")))
    count_summary.to_csv(args.out_root / "count_error_summary.csv", index=False)

